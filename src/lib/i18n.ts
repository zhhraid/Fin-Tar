export type TranslationKey = keyof typeof translations.id;

export function t(key: TranslationKey, lang: Language = getLanguage(), params?: Record<string, string | number>): string {
  const table = translations[lang] || translations.id;
  let str: string = (table as Record<string, string>)[key] || (translations.id as Record<string, string>)[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
    }
  }
  return str;
}

export function useTranslation() {
  const lang = useLanguage();
  return {
    lang,
    t: (key: TranslationKey, params?: Record<string, string | number>) => t(key, lang, params),
  };
}
